def freeze_artifact(path, blob, provenance):
    """Explicit generation/capture mode only; refuse replacement of existing bytes."""
    digest = hashlib.sha256(blob).hexdigest()
    expected = {"sha256": digest, "provenance": provenance, "expected": decode(blob)}
    path.parent.mkdir(parents=True, exist_ok=True)
    for target, content in [(path, blob), (path.with_suffix(".sha256"), (digest + "\n").encode()),
                            (path.with_suffix(".json"), (json.dumps(expected, indent=2, sort_keys=True) + "\n").encode())]:
        if target.exists():
            if target.read_bytes() != content:
                raise ValueError(f"refusing to overwrite differing artifact: {target}")
        else:
            target.write_bytes(content)


def verify():
    paths = sorted(ROOT.rglob("*.bin"))
    if not paths:
        raise ValueError("no fixtures")
    for path in paths:
        blob = path.read_bytes()
        digest = hashlib.sha256(blob).hexdigest()
        expected = json.loads(path.with_suffix(".json").read_text())
        assert path.with_suffix(".sha256").read_text().strip() == digest, path
        assert expected["sha256"] == digest, path
        actual = decode(blob)
        assert expected["expected"] == actual, (path, actual, expected["expected"])
        print(f"PASS {path.relative_to(ROOT)} SHA/header/framing/layout/slices/padding/count")
    print(f"ORACLE PASS={len(paths)} FAIL=0 (independent Python stdlib)")


def capture_softflowd(executable, evidence_dir, commit, archive_sha, source_dir):
    """Test-only loopback collector; not a production/live ingestion API."""
    executable = executable.resolve(strict=True)
    pcap = Path(__file__).parent / "fixtures" / "pcap" / "m1d_synthetic.pcap"
    license_bytes = (source_dir / "LICENSE").read_bytes()
    version = subprocess.run([str(executable), "-h"], capture_output=True, text=True, check=False)
    receiver = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    receiver.bind(("127.0.0.1", 0))
    receiver.settimeout(0.2)
    port = receiver.getsockname()[1]
    command = [str(executable), "-d", "-r", str(pcap), "-v", "9", "-P", "udp", "-n", f"127.0.0.1:{port}"]
    producer = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    captures = []
    deadline = time.monotonic() + 30
    try:
        while time.monotonic() < deadline:
            try:
                blob, peer = receiver.recvfrom(65536)
                if peer[0] != "127.0.0.1":
                    raise ValueError("non-loopback exporter")
                captures.append(blob)
                if len(captures) > 64:
                    raise ValueError("bounded evidence capture exceeded 64 packets")
            except socket.timeout:
                if producer.poll() is not None:
                    break
        if producer.poll() is None:
            raise TimeoutError("softflowd did not terminate")
        stdout, stderr = producer.communicate(timeout=2)
        if producer.returncode != 0 or not captures:
            raise ValueError(f"exporter failed/no packets: rc={producer.returncode}; {stderr.decode(errors='replace')[:2000]}")
        print("PRODUCER_STDOUT", stdout.decode(errors="replace"))
        print("PRODUCER_STDERR", stderr.decode(errors="replace"))
        for ordinal, blob in enumerate(captures):
            decoded = decode(blob)
            if "error" in decoded or decoded["reset"]:
                raise ValueError(f"capture failed independent structural qualification: {decoded}")
            provenance = {"producer": "irino/softflowd", "commit": commit, "source_archive_sha256": archive_sha,
                          "source_url": f"https://github.com/irino/softflowd/tree/{commit}",
                          "license": "BSD-2-Clause plus bundled notices; see upstream LICENSE", "license_sha256": hashlib.sha256(license_bytes).hexdigest(),
                          "license_text": license_bytes.decode(), "version_help": (version.stdout + version.stderr),
                          "generation_command": command, "pcap_sha256": hashlib.sha256(pcap.read_bytes()).hexdigest(),
                          "capture_ordinal": ordinal, "sensitive_data": False,
                          "qualification": "raw loopback UDP from pinned independently built exporter, independent Python structural decode"}
            freeze_artifact(evidence_dir / f"softflowd_{ordinal:03}.bin", blob, provenance)
            print("CAPTURE", ordinal, len(blob), hashlib.sha256(blob).hexdigest(), decoded["count"])
    finally:
        receiver.close()
        if producer.poll() is None:
            producer.kill()
            producer.communicate()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate", action="store_true")
    parser.add_argument("--describe", type=Path)
    parser.add_argument("--capture-softflowd", type=Path)
    parser.add_argument("--evidence-dir", type=Path)
    parser.add_argument("--producer-commit")
    parser.add_argument("--archive-sha")
    parser.add_argument("--producer-source-dir", type=Path)
    args = parser.parse_args()
    if args.generate:
        for name, blob in synthetic_cases().items():
            freeze_artifact(ROOT / (name + ".bin"), blob,
                            {"producer": "independent Python struct/manual synthetic builder", "command":
                             "python ingestion/tests/netflow_v9_fixture_oracle.py --generate", "sensitive_data": False})
    if args.capture_softflowd:
        if not all([args.evidence_dir, args.producer_commit, args.archive_sha, args.producer_source_dir]):
            parser.error("capture requires evidence-dir, producer-commit, archive-sha and producer-source-dir")
        capture_softflowd(args.capture_softflowd, args.evidence_dir, args.producer_commit, args.archive_sha, args.producer_source_dir)
    elif args.describe:
        print(json.dumps(decode(args.describe.read_bytes()), indent=2, sort_keys=True))
    else:
        verify()


if __name__ == "__main__":
    main()
