def decode(blob):
    if len(blob) < 20:
        return {"error": "TruncatedHeader"}
    version, count, uptime, secs, seq, source = struct.unpack_from("!HHIIII", blob)
    if version != 9:
        return {"error": "UnsupportedVersion"}
    result = {"header": [version, count, uptime, secs, seq, source], "flowsets": []}
    offset = 20
    frames = []
    while offset < len(blob):
        if len(blob) - offset < 4:
            return {"error": "TrailingPacketBytes"}
        ident, length = struct.unpack_from("!HH", blob, offset)
        if length < 4:
            return {"error": "InvalidFlowSetLength"}
        if offset + length > len(blob):
            return {"error": "FlowSetBeyondPacket"}
        frames.append((ident, length, offset, blob[offset + 4:offset + length]))
        offset += length
    if not frames:
        return {"error": "MissingFlowSets"}
    templates = {}
    parsed = 0
    reliable = True
    stopped = False
    for ordinal, (ident, length, offset, payload) in enumerate(frames):
        fs = {"id": ident, "length": length, "offset": offset, "ordinal": ordinal,
              "raw": payload.hex(), "processed": not stopped}
        result["flowsets"].append(fs)
        if ident < 2:
            fs.update(kind="templates", records=[], padding="")
            pos = 0
            while pos < len(payload):
                rest = payload[pos:]
                if len(rest) <= 3:
                    fs["padding"] = rest.hex()
                    if any(rest):
                        reliable = False
                        stopped = True
                    break
                header_len = 4 if ident == 0 else 6
                tid = struct.unpack_from("!H", rest)[0]
                if len(rest) < header_len:
                    reliable = False
                    stopped = True
                    fs["records"].append({"id": tid, "ordinal": len(fs["records"]),
                                          "offset": offset + 4 + pos, "state": "Rejected",
                                          "scope": 0, "count": 0, "fields": [], "raw": rest.hex()})
                    break
                if ident == 0:
                    nfields = struct.unpack_from("!H", rest, 2)[0]
                    scope, descriptor_len, malformed = 0, nfields * 4, False
                else:
                    scope_len, option_len = struct.unpack_from("!HH", rest, 2)
                    scope = scope_len // 4
                    descriptor_len = scope_len + option_len
                    nfields = scope + option_len // 4
                    malformed = bool(scope_len % 4 or option_len % 4)
                extent = header_len + descriptor_len
                trusted = extent <= len(rest)
                fields = []
                if trusted and not malformed:
                    fields = [list(struct.unpack_from("!HH", rest, p))
                              for p in range(header_len, extent, 4)]
                supported = trusted and not malformed and tid >= 256 and 0 < nfields <= 256
                supported = supported and all(width > 0 for _, width in fields)
                supported = supported and 0 < sum(width for _, width in fields) <= 65531
                state = "Unprocessed" if stopped else "Applied" if supported else "Rejected"
                raw = rest[:extent] if trusted else rest
                rec = {"id": tid, "ordinal": len(fs["records"]), "offset": offset + 4 + pos,
                       "scope": scope, "count": nfields, "fields": fields, "state": state, "raw": raw.hex()}
                fs["records"].append(rec)
                if not stopped:
                    if supported:
                        templates[tid] = (ident, scope, fields)
                        parsed += 1
                    else:
                        reliable = False
                        if trusted and tid >= 256:
                            templates.pop(tid, None)
                        else:
                            stopped = True
                if not trusted:
                    break
                pos += extent
            if not fs["records"]:
                reliable = False
                stopped = True
        elif ident < 256:
            fs["kind"] = "reserved"
            if not stopped:
                reliable = False
        else:
            fs.update(kind="data", state="Unprocessed", records=[], padding="")
            if stopped:
                continue
            if ident not in templates:
                reliable = False
                fs["state"] = "SkippedUnknown"
                continue
            template_kind, scope, fields = templates[ident]
            width = sum(length for _, length in fields)
            nrecords, remainder = divmod(len(payload), width)
            padding = payload[nrecords * width:]
            fs["padding"] = padding.hex()
            if not nrecords or remainder > 3 or any(padding):
                reliable = False
                fs["state"] = "Rejected"
                continue
            fs["state"] = "Decoded"
            parsed += nrecords
            for record_ordinal in range(nrecords):
                raw = payload[record_ordinal * width:(record_ordinal + 1) * width]
                values = []
                field_offset = 0
                for field_ordinal, (field_id, field_width) in enumerate(fields):
                    role = "Data" if template_kind == 0 else "Scope" if field_ordinal < scope else "Option"
                    values.append([field_id, field_width, role, raw[field_offset:field_offset + field_width].hex()])
                    field_offset += field_width
                fs["records"].append({"ordinal": record_ordinal, "offset": offset + 4 + record_ordinal * width,
                                      "raw": raw.hex(), "fields": values})
    result["count"] = "Inconclusive" if not reliable else "Match" if count == parsed else "Mismatch"
    result["parsed_count"] = parsed if reliable else None
    result["reset"] = stopped
    return result


def frame(ident, payload):
    return struct.pack("!HH", ident, 4 + len(payload)) + payload


def template(ident, fields):
    return struct.pack("!HH", ident, len(fields)) + b"".join(struct.pack("!HH", *f) for f in fields)


def options(ident, scopes, fields):
    return struct.pack("!HHH", ident, len(scopes) * 4, len(fields) * 4) + b"".join(
        struct.pack("!HH", *f) for f in scopes + fields)


def packet(count, frames, *, source=42, seq=123, secs=100, uptime=9000):
    return struct.pack("!HHIIII", 9, count, uptime, secs, seq, source) + b"".join(frames)


