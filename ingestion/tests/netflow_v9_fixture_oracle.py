"""Independent stdlib-only v9 structural oracle and explicit synthetic builder.

No Rust/PyO3 imports, no Rust output used for expectations. Default mode checks
existing bytes, SHA sidecars and frozen expected structures without writing.
--generate explicitly creates only the enumerated synthetic artifacts. Genuine
exporter captures are never generated by that mode. --describe prints structure.
"""

