def lookup(threat_class: str | None) -> ThreatKnowledge | None:
    """Reference material for *threat_class*, or ``None`` if we have none.

    ``None`` rather than a placeholder: an entry we do not have is answered
    from retrieved alerts alone, which is a smaller answer but a true one.
    """
    if not threat_class:
        return None
    return KNOWLEDGE.get(threat_class)
