"""What each threat class *is*, for the questions the alert store cannot answer.

Retrieval answers "how many", "which host", "when". It cannot answer "what is a
DGA and why does it matter", because that is not a fact about any row - it is
background an analyst is assumed to have and a judge watching the demo is not.
This module is that background, and nothing else.

Three rules govern what may be written here, and the tests enforce all three.

**Keyed on the frozen enum.** The keys are the exact ``threat_class`` values
from ``backend/app/schemas/enums.py::ThreatClass``. A class with no entry falls
back to live retrieval alone rather than to a guess, and ``test_knowledge.py``
fails if the two vocabularies ever drift apart.

**Evidence fields are the real ones.** Every name in ``evidence_fields``
appears in ``backend/fixtures/sample_by_class.json`` for that class. They are
what the detector actually emits, so an analyst reading "look at
``interval_cv``" can go and look at ``interval_cv``.

**No measurements.** Not one sentence here carries a threshold, a rate, a
duration or a count. That is not a style preference - it is what keeps the
verifier honest. ``grounding.unsupported_numbers()`` builds its allowed set
from every figure in the fact sheet, so a line here reading "beacons typically
every sixty seconds" would license the model to state sixty as though something
had measured it. Every number in an answer must come from a stored field, so
every number stays out of this file. MITRE technique ids are the one exception:
they are identifiers, not measurements, and the model may repeat one precisely
because the sheet asserted it.
"""

from __future__ import annotations

from dataclasses import dataclass

__all__ = ["ThreatKnowledge", "KNOWLEDGE", "lookup"]


@dataclass(frozen=True, slots=True)
class ThreatKnowledge:
    """Reference material for one threat class.

    The fields are ordered the way an analyst reads them: what it is, what the
    attacker gets out of it, where to look, what it maps to, and - the one most
    often missing from a console - what benign traffic looks the same.
    """

    label: str
    #: One sentence: what the behaviour is, in the words an operator would use.
    summary: str
    #: Why an attacker does this, and what it buys them.
    intent: str
    #: How the detection layer recognises it, qualitatively.
    detection: str
    #: Evidence keys carrying the signal, in the order worth reading them.
    evidence_fields: tuple[str, ...]
    #: MITRE ATT&CK technique ids, matching what the detectors put on the alert.
    mitre: tuple[str, ...]
    #: What an analyst should establish next. Never an instruction to act on
    #: traffic: this system cannot send anything toward the monitored network,
    #: so "block it" would be a false statement about the product.
    investigate: str
    #: Legitimate traffic that produces the same shape. The single most useful
    #: line on a console that fires on behaviour rather than signatures.
    benign_lookalike: str


