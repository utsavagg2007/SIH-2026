#!/usr/bin/env python3
"""ROC-AUC / PR-AUC for the DGA model on REAL domains.

    python tools/dga_real_eval.py --model artifacts/dga_model.joblib \
        --umbrella <umbrella top-1m zip>

The flow-level public datasets carry no DNS query strings, so `dga_domain`
cannot be evaluated from them at all. It can be evaluated directly, though,
because its input is a domain name and real domain ground truth is obtainable:

* **positives** - real DGA domains from malware families the model was
  **never trained on**. `build_dataset.DEFAULT_FAMILIES` names the 27 families
  the corpus uses; the baderj repository publishes ~40, so the remainder
  (bumblebee, murofet, ranbyus, pykspa, kraken, padcrypt, dnschanger, ...) are
  genuine unseen-family positives generated by real malware algorithms.
* **negatives** - real hostnames from the Cisco Umbrella top 1M, which is what
  public resolvers actually saw, sampled from the whole list rather than the
  head. Anything already in the training CSV is excluded.

This is a stronger test than the training report's own held-out split: those
negatives were Tranco registrable domains drawn from the same slice the model
trained on, and these are resolver-observed FQDNs including CDN hostnames,
subdomains and junk at their real proportions.

What it still is not: the positives are algorithm *reimplementations*, so they
are the names the malware would generate rather than names observed resolving
in a live incident. Getting the latter needs a commercial or CERT feed.
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import random
import sys
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "detection"))

from detection_core.ml.dga.data.build_dataset import (  # noqa: E402
    BADERJ_RAW, DEFAULT_FAMILIES, _all_baderj_families, _get,
)

#: Defined here rather than imported: the CDN corpus work that added this
#: constant to build_dataset lives on another branch, and this evaluation has
#: to run against either version of the trainer.
UMBRELLA_URL = "https://s3-us-west-1.amazonaws.com/umbrella-static/top-1m.csv.zip"
from detection_core.ml.dga.features import normalize_domain  # noqa: E402
from detection_core.ml.dga.model import DGAModel  # noqa: E402

THRESHOLDS = [0.50, 0.55, 0.60, 0.65, 0.70, 0.75, 0.80, 0.85, 0.90]


def norm(raw: str) -> str | None:
    try:
        return normalize_domain(raw)
    except (TypeError, ValueError):
        return None


def unseen_family_domains(timeout: float, cap: int) -> dict[str, list[str]]:
    trained = set(DEFAULT_FAMILIES)
    families = [f for f in _all_baderj_families(timeout) if f not in trained]
    out: dict[str, list[str]] = {}
    for fam in families:
        try:
            text = _get(BADERJ_RAW.format(family=fam), timeout).decode("utf-8", "replace")
        except Exception as exc:  # noqa: BLE001
            print(f"    {fam}: fetch failed ({type(exc).__name__})", file=sys.stderr)
            continue
        seen, keep = set(), []
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            d = norm(line)
            if d and d not in seen:
                seen.add(d)
                keep.append(d)
            if len(keep) >= cap:
                break
        if keep:
            out[fam] = keep
    return out


def umbrella_sample(source: Path | None, n: int, seed: int, timeout: float) -> list[str]:
    if source and source.is_file():
        payload = source.read_bytes()
    else:
        payload = _get(UMBRELLA_URL, timeout)
    with zipfile.ZipFile(io.BytesIO(payload)) as z:
        text = z.read(z.namelist()[0]).decode("utf-8", "replace")
    rows = [r[-1].strip() for r in csv.reader(io.StringIO(text)) if r]
    rng = random.Random(seed)
    rng.shuffle(rows)
    out, seen = [], set()
    for host in rows:
        d = norm(host)
        if d and d not in seen:
            seen.add(d)
            out.append(d)
        if len(out) >= n:
            break
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--model", action="append", required=True,
                    help="path[:label]; repeat to compare models")
    ap.add_argument("--dataset-csv", action="append", default=None,
                    help="training CSV whose domains are excluded from the negatives; "
                         "repeat when comparing models trained on different corpora")
    ap.add_argument("--umbrella", default=None, help="local top-1m.csv.zip (else downloaded)")
    ap.add_argument("--negatives", type=int, default=40000)
    ap.add_argument("--per-family-cap", type=int, default=500)
    ap.add_argument("--seed", type=int, default=20260902)
    ap.add_argument("--timeout", type=float, default=60.0)
    ap.add_argument("-o", "--output", default=None)
    args = ap.parse_args()

    from sklearn.metrics import average_precision_score, roc_auc_score

    print("fetching real unseen-family DGA domains ...", file=sys.stderr)
    fams = unseen_family_domains(args.timeout, args.per_family_cap)
    pos = [d for v in fams.values() for d in v]
    print(f"  {len(pos)} domains from {len(fams)} families never trained on",
          file=sys.stderr)

    print("sampling real benign hostnames from Umbrella ...", file=sys.stderr)
    neg = umbrella_sample(Path(args.umbrella) if args.umbrella else None,
                          args.negatives, args.seed, args.timeout)

    csvs = args.dataset_csv or [str(
        ROOT / "detection/detection_core/ml/dga/data/dga_dataset.sample.csv")]
    trained_domains: set[str] = set()
    for c in csvs:
        p = Path(c)
        if p.is_file():
            with p.open(encoding="utf-8") as fh:
                for row in csv.DictReader(fh):
                    trained_domains.add(row["domain"])
    print(f"  excluding {len(trained_domains)} domains seen in {len(csvs)} training CSV(s)",
          file=sys.stderr)
    before = len(neg)
    neg = [d for d in neg if d not in trained_domains]
    pos_overlap = [d for d in pos if d in trained_domains]
    pos = [d for d in pos if d not in trained_domains]
    print(f"  {len(neg)} benign (dropped {before-len(neg)} already in training)",
          file=sys.stderr)
    if pos_overlap:
        print(f"  dropped {len(pos_overlap)} positives that were in training",
              file=sys.stderr)

    domains = pos + neg
    y = [1] * len(pos) + [0] * len(neg)

    results = {}
    for spec in args.model:
        path, _, label = spec.partition(":")
        label = label or Path(path).stem
        model = DGAModel.load(Path(path))
        scores = model.predict_scores(domains)
        roc = roc_auc_score(y, scores)
        pr = average_precision_score(y, scores)
        sweep = []
        for t in THRESHOLDS:
            tp = sum(1 for s, yy in zip(scores, y) if s >= t and yy == 1)
            fp = sum(1 for s, yy in zip(scores, y) if s >= t and yy == 0)
            fn = sum(1 for s, yy in zip(scores, y) if s < t and yy == 1)
            prec = tp / (tp + fp) if (tp + fp) else None
            rec = tp / (tp + fn) if (tp + fn) else None
            f1 = 2 * prec * rec / (prec + rec) if (prec and rec) else None
            sweep.append({"threshold": t, "precision": prec, "recall": rec, "f1": f1,
                          "tp": tp, "fp": fp, "fn": fn,
                          "fp_per_1000_benign": 1000.0 * fp / len(neg)})
        per_family = {}
        i = 0
        for fam, doms in fams.items():
            doms = [d for d in doms if d not in trained_domains]
            if not doms:
                continue
            sub = scores[i:i + len(doms)]
            i += len(doms)
            per_family[fam] = {
                "n": len(doms),
                "recall@0.75": sum(1 for s in sub if s >= 0.75) / len(sub),
                "recall@0.65": sum(1 for s in sub if s >= 0.65) / len(sub),
                "mean": sum(sub) / len(sub),
            }
        results[label] = {"roc_auc": roc, "pr_auc": pr, "sweep": sweep,
                          "per_family": per_family}

    print()
    print("DGA MODEL ON REAL DOMAINS")
    print("=" * 100)
    print(f"  positives : {len(pos)} domains, {len(fams)} malware families NEVER trained on")
    print(f"  negatives : {len(neg)} real hostnames sampled from the Cisco Umbrella top 1M")
    print()
    for label, r in results.items():
        print(f"  --- {label} ---")
        print(f"      ROC-AUC {r['roc_auc']:.4f}    PR-AUC {r['pr_auc']:.4f}")
        print(f"      {'thr':>5s} {'precision':>10s} {'recall':>8s} {'F1':>7s} "
              f"{'FP':>7s} {'FP/1k benign':>13s}")
        for s in r["sweep"]:
            if s["threshold"] not in (0.50, 0.65, 0.75, 0.85):
                continue
            def f(v, w=8, p=4):
                return f"{'-':>{w}}" if v is None else f"{v:{w}.{p}f}"
            print(f"      {s['threshold']:5.2f} {f(s['precision'],10)} {f(s['recall'])} "
                  f"{f(s['f1'],7)} {s['fp']:7d} {s['fp_per_1000_benign']:13.2f}")
        print()

    print("  PER-FAMILY RECALL @0.75 (real malware families, none seen in training)")
    first = next(iter(results.values()))
    for fam, v in sorted(first["per_family"].items(), key=lambda kv: -kv[1]["recall@0.75"]):
        bars = "#" * int(v["recall@0.75"] * 30)
        print(f"    {fam:26s} n={v['n']:5d}  {v['recall@0.75']:.3f}  {bars}")

    payload = {
        "kind": "dga_model_real_domain_evaluation",
        "positives": len(pos), "negatives": len(neg),
        "families": {k: len(v) for k, v in fams.items()},
        "negative_source": "Cisco Umbrella top 1M (resolver-observed FQDNs)",
        "results": results,
        "caveat": "Positives are domains produced by public reimplementations of real "
                  "malware DGAs, not names observed resolving in a live incident.",
    }
    if args.output:
        Path(args.output).write_text(json.dumps(payload, indent=2), encoding="utf-8")
        print(f"\n[+] -> {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
